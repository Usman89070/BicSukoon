// Writes dist/.htaccess so Apache / LiteSpeed hosts (Hostinger, GoDaddy cPanel) route the
// single-page apps correctly: starting page at /, websites under /bic/ and
// /sukoon/. Written once at the dist root (not via public/, which would copy
// it into the sub-site folders and override these rules there).
import { writeFileSync, existsSync } from 'node:fs'

if (!existsSync('dist/index.html')) {
  console.error('[htaccess] dist/index.html not found, run the full build first.')
  process.exit(1)
}

writeFileSync(
  'dist/.htaccess',
  `# Generated by scripts/write-htaccess.mjs
Options -MultiViews
AddType video/mp4 .mp4 .m4v
AddType video/webm .webm
DirectoryIndex index.html index.php

# Bookkeeping file of the automatic FTP deploy (GitHub Action): not public
<Files ".ftp-deploy-sync-state.json">
  Require all denied
</Files>

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # sitemap.xml and robots.txt are written by PHP for whatever domain the
  # site is opened on (api/sitemap.php, api/robots.php)
  RewriteRule ^robots\\.txt$ api/robots.php [L]
  RewriteRule ^sitemap\\.xml$ api/sitemap.php?site=index [L]
  RewriteRule ^sitemap-home\\.xml$ api/sitemap.php?site=home [L]
  RewriteRule ^(bic|sukoon)/sitemap\\.xml$ api/sitemap.php?site=$1 [L]

  # Existing files and folders (assets, favicons) are served as-is
  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]

  # Videos not found in /videos/ are served from bic-videos/ (outside the
  # website folder, kept on redeploys) by api/video.php
  RewriteRule ^videos/(.+)$ api/video.php?f=$1 [L,QSA,B]

  # Every other URL is a page inside one of the apps
  RewriteRule ^bic(/.*)?$ bic/index.html [L]
  RewriteRule ^sukoon(/.*)?$ sukoon/index.html [L]
  RewriteRule ^ index.html [L]
</IfModule>

# Always fetch the latest HTML so new deploys show immediately
<IfModule mod_headers.c>
  <FilesMatch "index\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  <FilesMatch "\\.(mp4|m4v|webm|mov)$">
    Header set Cache-Control "public, max-age=86400"
  </FilesMatch>
</IfModule>
`,
)
console.log('[htaccess] Wrote dist/.htaccess')

// The same routing for Windows / IIS hosting (e.g. GoDaddy Plesk on Windows),
// which reads web.config instead of .htaccess. Needs the IIS URL Rewrite module.
writeFileSync(
  'dist/web.config',
  `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/write-htaccess.mjs (IIS version of .htaccess) -->
<configuration>
  <system.webServer>
    <defaultDocument>
      <files>
        <clear />
        <add value="index.html" />
        <add value="index.php" />
      </files>
    </defaultDocument>
    <staticContent>
      <remove fileExtension=".mp4" />
      <mimeMap fileExtension=".mp4" mimeType="video/mp4" />
      <remove fileExtension=".m4v" />
      <mimeMap fileExtension=".m4v" mimeType="video/mp4" />
      <remove fileExtension=".webm" />
      <mimeMap fileExtension=".webm" mimeType="video/webm" />
      <remove fileExtension=".webp" />
      <mimeMap fileExtension=".webp" mimeType="image/webp" />
    </staticContent>
    <rewrite>
      <rules>
        <rule name="robots" stopProcessing="true">
          <match url="^robots\\.txt$" />
          <action type="Rewrite" url="api/robots.php" />
        </rule>
        <rule name="sitemap-index" stopProcessing="true">
          <match url="^sitemap\\.xml$" />
          <action type="Rewrite" url="api/sitemap.php?site=index" appendQueryString="false" />
        </rule>
        <rule name="sitemap-home" stopProcessing="true">
          <match url="^sitemap-home\\.xml$" />
          <action type="Rewrite" url="api/sitemap.php?site=home" appendQueryString="false" />
        </rule>
        <rule name="sitemap-site" stopProcessing="true">
          <match url="^(bic|sukoon)/sitemap\\.xml$" />
          <action type="Rewrite" url="api/sitemap.php?site={R:1}" appendQueryString="false" />
        </rule>
        <rule name="existing-files" stopProcessing="true">
          <match url=".*" />
          <conditions logicalGrouping="MatchAny">
            <add input="{REQUEST_FILENAME}" matchType="IsFile" />
            <add input="{REQUEST_FILENAME}" matchType="IsDirectory" />
          </conditions>
          <action type="None" />
        </rule>
        <rule name="videos" stopProcessing="true">
          <match url="^videos/(.+)$" />
          <action type="Rewrite" url="api/video.php?f={UrlEncode:{R:1}}" />
        </rule>
        <rule name="bic-app" stopProcessing="true">
          <match url="^bic(/.*)?$" />
          <action type="Rewrite" url="bic/index.html" />
        </rule>
        <rule name="sukoon-app" stopProcessing="true">
          <match url="^sukoon(/.*)?$" />
          <action type="Rewrite" url="sukoon/index.html" />
        </rule>
        <rule name="portal" stopProcessing="true">
          <match url=".*" />
          <action type="Rewrite" url="index.html" />
        </rule>
      </rules>
    </rewrite>
  </system.webServer>
</configuration>
`,
)
console.log('[htaccess] Wrote dist/web.config')
